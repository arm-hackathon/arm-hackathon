"""BDM-v1 Scenario Family Generator v2 (Issue #72).

Deterministic generator for causally distinct Habitat V2 development families
with mechanism-held-out, group-disjoint custody partitions. A family scenario
is a pure function of ``(generator version, registry seed, group index,
sensor variant, feasibility attempt)``; identical inputs regenerate
byte-identical scenario JSON.

Design rules enforced here:

- Parameter draws come only from declared bands: generator-variable records of
  the Issue #71 provenance manifest plus the explicitly declared generator
  vocabularies in this module (fault multipliers/windows, sensor-defect
  magnitudes, initial oxygen regime bands). No undeclared knob exists.
- Grouping follows the Issue #70 contract: the causal group is the independent
  unit; paired sensor variants and every counterfactual branch of one causal
  starting state stay in the same group.
- Operating-mode labels are context only; every physical load or command
  change is explicit in the timeline.
- BLIND_FINAL families are generated by the same deterministic stream and are
  sealed by digest in the custody registry; no blind outcome is ever computed
  in development.

This module never runs the plant, trains a model, or opens blind outcomes.
HMC remains the sole proposal-arbitration, final-command, plant-step, and
replay authority in every downstream study.
"""

